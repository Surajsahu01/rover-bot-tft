#!/usr/bin/env python3
"""Generates main/boards/rover-bot/rover_font.h (monospace bitmap fonts for the OLED)."""
from PIL import Image, ImageDraw, ImageFont
import sys
TTF_BOLD = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf"
TTF_REG = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
FONTS = [  # name, pixel size, cell w, cell h, chars
    ("S", 10, 6, 10, [chr(c) for c in range(32, 127)]),
    ("M", 12, 7, 13, [chr(c) for c in range(32, 127)]),
    ("L", 33, 20, 28, [chr(c) for c in range(32, 127)][:0] + list(" 0123456789:-.")),
]
out = ["// Generated by tools/gen_font.py - do not edit.", "#pragma once", "#include <stdint.h>",
       "struct RoverFont { int w, h, first, count; const uint32_t* rows; const char* chars; };", ""]
preview = Image.new("L", (260, 140), 255)
pd = ImageDraw.Draw(preview)
py = 2
for name, size, cw, ch, chars in FONTS:
    font = ImageFont.truetype(TTF_BOLD if name == 'L' else TTF_REG, size)
    asc, desc = font.getmetrics()
    base = min(ch - 1, asc) if name != "L" else ch - 1
    rows = []
    for c in chars:
        im = Image.new("1", (cw, ch), 0)
        d = ImageDraw.Draw(im); d.fontmode = "1"
        d.text((0, base), c, font=font, fill=1, anchor="ls")
        for y in range(ch):
            v = 0
            for x in range(cw):
                if im.getpixel((x, y)): v |= 1 << (cw - 1 - x)
            rows.append(v)
    out.append(f"static const uint32_t kFont{name}Rows[] = {{")
    for i in range(0, len(rows), 8):
        out.append("    " + ", ".join(f"0x{v:X}" for v in rows[i:i+8]) + ",")
    out.append("};")
    chars_c = "".join(chars).replace("\\", "\\\\").replace('"', '\\"')
    out.append(f'static const RoverFont kFont{name} = {{{cw}, {ch}, {ord(chars[0])}, {len(chars)}, kFont{name}Rows, "{chars_c}"}};')
    out.append("")
    # preview
    sample = "192.168.1.45:8080" if name != "L" else "12:45"
    x = 2
    for c in sample:
        i = chars.index(c) if c in chars else 0
        for y in range(ch):
            v = rows[i*ch+y]
            for xx in range(cw):
                if (v >> (cw-1-xx)) & 1: pd.point((x+xx, py+y), fill=0)
        x += cw
    py += ch + 6
open("/home/claude/rover/main/boards/rover-bot/rover_font.h", "w").write("\n".join(out) + "\n")
preview = preview.resize((preview.width*4, preview.height*4), Image.NEAREST)
preview.save("/tmp/font_preview.png")
print("ok")
